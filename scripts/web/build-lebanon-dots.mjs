#!/usr/bin/env node
// Builds src/design/lebanon-dots.generated.ts: every place of the places list as one dot of a static map of
// Lebanon, plus the coordinates of the pilot villages. READ-ONLY on supabase/seed/places/ (data freeze, DECISIONS §31).
// Run again after the data finalisation session (D) replaces the places list:  node scripts/web/build-lebanon-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";

const csv = readFileSync("supabase/seed/places/places.csv", "utf8");

// Minimal CSV reader (quoted fields, doubled quotes, embedded newlines).
function parse(text) {
  const rows = [];
  let row = [],
    cell = "",
    q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ",") {
      row.push(cell);
      cell = "";
    } else if (c === "\n") {
      row.push(cell);
      rows.push(row);
      row = [];
      cell = "";
    } else if (c !== "\r") cell += c;
  }
  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }
  return rows;
}

const [head, ...body] = parse(csv);
const ix = Object.fromEntries(head.map((h, i) => [h, i]));
const places = body
  .filter((r) => r.length > ix.lon && r[ix.lat] && r[ix.lon])
  .map((r) => ({ id: r[ix.id], lat: Number(r[ix.lat]), lon: Number(r[ix.lon]) }))
  .filter((p) => Number.isFinite(p.lat) && Number.isFinite(p.lon));

// Equirectangular, corrected for latitude. W x H is the SVG viewBox.
export const BOUNDS = { minLat: 33.0, maxLat: 34.72, minLon: 35.05, maxLon: 36.65 };
const K = Math.cos(((BOUNDS.minLat + BOUNDS.maxLat) / 2) * (Math.PI / 180));
const SCALE = 520; // units per degree of latitude
const W = Math.round((BOUNDS.maxLon - BOUNDS.minLon) * K * SCALE);
const H = Math.round((BOUNDS.maxLat - BOUNDS.minLat) * SCALE);
const project = (lat, lon) => [
  Math.round((lon - BOUNDS.minLon) * K * SCALE),
  Math.round((BOUNDS.maxLat - lat) * SCALE),
];

const pts = places.map((p) => project(p.lat, p.lon));
// De-duplicate identical rounded positions and order top-to-bottom for small relative moves.
const seen = new Set();
const uniq = pts.filter(([x, y]) =>
  seen.has(x * 10000 + y) ? false : (seen.add(x * 10000 + y), true),
);
uniq.sort((a, b) => a[1] - b[1] || a[0] - b[0]);
let d = "";
let px = 0,
  py = 0;
for (const [x, y] of uniq) {
  d += `m${x - px} ${y - py}h0`;
  px = x;
  py = y;
}

const PILOT = ["LB-CHF-BAAKLINE", "LB-CHF-BAKAATA", "LB-CHF-SEMQANIEH", "LB-CHF-BEITEDDINE"];
const pilot = Object.fromEntries(
  PILOT.map((id) => {
    const p = places.find((x) => x.id === id);
    if (!p) throw new Error(`pilot place ${id} missing from the places list`);
    return [id, { lat: p.lat, lon: p.lon }];
  }),
);

const out = `// GENERATED by scripts/web/build-lebanon-dots.mjs from supabase/seed/places/places.csv. Do not edit by hand.
// One dot per place of the places list, drawn as a single path (zero-length segments with round caps).
// Re-run the script after the data finalisation session (DECISIONS §31) replaces the places list.
export const LEBANON_MAP = {
  width: ${W},
  height: ${H},
  bounds: ${JSON.stringify(BOUNDS)},
  lonFactor: ${K.toFixed(5)},
  scale: ${SCALE},
  dots: ${JSON.stringify(d)},
  count: ${uniq.length},
} as const;

/** The first marketing area (DECISIONS §1): the four Shouf villages. Their coordinates come from the places list. */
export const PILOT_PLACES: Record<string, { lat: number; lon: number }> = ${JSON.stringify(pilot, null, 2)};
`;
writeFileSync("src/design/lebanon-dots.generated.ts", out);
console.log(`dots: ${uniq.length}, viewBox ${W}x${H}, path ${d.length} chars`);
