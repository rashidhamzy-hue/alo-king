// Draws the console's app icons (an "A" on the brand colour) and writes src/icons.ts. Pure Node, no dependencies:
//   node apps/console/scripts/make-icons.mjs
// The glyph stays inside the central 80% circle, so the same image serves as a maskable icon (Android crops to a circle).
import { deflateSync } from "node:zlib";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const BG = [0x0f, 0x3d, 0x5e], FG = [0xff, 0xff, 0xff], GOLD = [0xf2, 0xa9, 0x00];
const legs = [[[0.5, 0.2], [0.29, 0.78]], [[0.5, 0.2], [0.71, 0.78]]], bar = [[0.385, 0.6], [0.615, 0.6]], W = 0.09;
const dist = (px, py, [[ax, ay], [bx, by]]) => {
  const dx = bx - ax, dy = by - ay, t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)));
  return Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
};
function pixel(x, y) {
  if (legs.some((s) => dist(x, y, s) <= W / 2)) return FG;
  if (dist(x, y, bar) <= W / 2.4) return GOLD;
  return BG;
}
function png(size) {
  const SS = 3, raw = Buffer.alloc(size * (size * 3 + 1));
  for (let j = 0; j < size; j++) {
    raw[j * (size * 3 + 1)] = 0;
    for (let i = 0; i < size; i++) {
      let r = 0, g = 0, b = 0;
      for (let a = 0; a < SS; a++) for (let c = 0; c < SS; c++) { const p = pixel((i + (a + 0.5) / SS) / size, (j + (c + 0.5) / SS) / size); r += p[0]; g += p[1]; b += p[2]; }
      const o = j * (size * 3 + 1) + 1 + i * 3, n = SS * SS;
      raw[o] = Math.round(r / n); raw[o + 1] = Math.round(g / n); raw[o + 2] = Math.round(b / n);
    }
  }
  const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
  const crc = (buf) => { let c = 0xffffffff; for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
  const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const cr = Buffer.alloc(4); cr.writeUInt32BE(crc(td)); return Buffer.concat([len, td, cr]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4); ihdr[8] = 8; ihdr[9] = 2;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))]);
}
const sizes = { "icon-192.png": 192, "icon-512.png": 512, "apple-touch-icon.png": 180 };
let out = "// Generated by scripts/make-icons.mjs: do not edit. The console's app icons as base64 PNG.\nexport const ICONS: Record<string, string> = {\n";
for (const [name, s] of Object.entries(sizes)) out += `  "${name}": "${png(s).toString("base64")}",\n`;
out += "};\n";
writeFileSync(fileURLToPath(new URL("../src/icons.ts", import.meta.url)), out);
console.log("wrote src/icons.ts");
