#!/usr/bin/env node
// Builds what the console serves from packages/ui (the website reads packages/ui at its own Astro build, through the Tailwind Vite plugin):
//   packages/ui/src/icons.ts               the Lucide icons the apps use, as inline SVG children (lucide-static, ISC)
//   apps/console/src/ui.generated.ts        the console's stylesheet, compiled by Tailwind v4 and minified (served as /console.css)
//   apps/console/src/fonts.generated.ts     the four font files as base64 (served as /fonts/*.woff2 from the Worker's own address)
//   packages/ui/crown.svg, apps/web/public/icons/icon.svg   the crown, in the token colours
// Run after any change to tokens.css, styles/*, the icon list below, or a class name used in apps/console/src:
//   node packages/ui/scripts/build.mjs            write
//   node packages/ui/scripts/build.mjs --check    write nothing; exit 1 if a generated file is out of date (CI runs this as a test)
// The PNG app icons need a browser to draw them: scripts/make-icons.mjs, run by hand when the crown or its colours change.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const UI = resolve(HERE, "..");
const ROOT = resolve(UI, "..", "..");
const check = process.argv.includes("--check");
const stale = [];
function emit(path, text) {
  const cur = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (cur === text) return;
  if (check) stale.push(path.replace(ROOT + "/", "")); else { writeFileSync(path, text); console.log("wrote", path.replace(ROOT + "/", "")); }
}

// ---------- tokens ----------
/** The light theme's values from tokens.css (the first :root block). */
export function readTokens() {
  const css = readFileSync(join(UI, "tokens.css"), "utf8");
  const root = /:root\s*\{([^}]*)\}/.exec(css)[1];
  return Object.fromEntries([...root.matchAll(/--ak-([a-z0-9-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}

/** Both themes, role by role, for the gallery and the contrast test. */
function tokensFile() {
  const css = readFileSync(join(UI, "tokens.css"), "utf8");
  const block = (re) => Object.fromEntries([...re.exec(css)[1].matchAll(/--ak-([a-z0-9-]+):\s*(#[0-9A-Fa-f]{6})\s*;/g)].map((m) => [m[1], m[2]]));
  const light = block(/:root\s*\{([^}]*)\}/), dark = { ...light, ...block(/:root\[data-theme="dark"\]\s*\{([^}]*)\}/) };
  emit(join(UI, "src", "tokens.generated.ts"), `// Generated by packages/ui/scripts/build.mjs from packages/ui/tokens.css: do not edit. The colour tokens of both themes.\nexport const LIGHT: Record<string, string> = ${JSON.stringify(light, null, 2)};\nexport const DARK: Record<string, string> = ${JSON.stringify(dark, null, 2)};\n`);
}

// ---------- icons ----------
