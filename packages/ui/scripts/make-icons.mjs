#!/usr/bin/env node
// Draws the app icons from the crown (packages/ui/src/crown.ts) in the token colours, and writes them where each app serves them:
//   apps/console/src/icons.ts           icon-192.png, icon-512.png, apple-touch-icon.png (180), as base64 (the Worker has no files)
//   apps/web/public/icons/              icon-192.png, icon-512.png, icon-maskable-512.png
// It needs a browser to turn the SVG into pixels (Playwright's Chromium), so it is run by hand, not in CI:
//   node packages/ui/scripts/make-icons.mjs
// Run it when the crown or its colours change, then commit the result. Every icon is the full ink square with the crown inside the
// central safe area, so the same image is right as a maskable icon (Android crops to a circle) and on an iPhone (which rounds it).
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { crownSources } from "./build.mjs";

const { chromium } = createRequire(import.meta.url)("playwright");
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const browser = await chromium.launch();
async function png(svg, size) {
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  await page.setContent(`<html><body style="margin:0"><img width="${size}" height="${size}" src="data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}"></body></html>`);
  const buf = await page.screenshot({ type: "png", clip: { x: 0, y: 0, width: size, height: size } });
  await page.close();
  return buf;
}
const { square, maskable } = crownSources;
const consoleIcons = { "icon-192.png": await png(maskable, 192), "icon-512.png": await png(maskable, 512), "apple-touch-icon.png": await png(square, 180) };
let out = "// Generated by packages/ui/scripts/make-icons.mjs: do not edit. The console's app icons (the crown, gold on ink) as base64 PNG.\nexport const ICONS: Record<string, string> = {\n";
for (const [name, buf] of Object.entries(consoleIcons)) out += `  "${name}": "${buf.toString("base64")}",\n`;
writeFileSync(join(ROOT, "apps", "console", "src", "icons.ts"), out + "};\n");
const web = join(ROOT, "apps", "web", "public", "icons");
writeFileSync(join(web, "icon-192.png"), await png(square, 192));
writeFileSync(join(web, "icon-512.png"), await png(square, 512));
writeFileSync(join(web, "icon-maskable-512.png"), await png(maskable, 512));
await browser.close();
console.log("icons written");
