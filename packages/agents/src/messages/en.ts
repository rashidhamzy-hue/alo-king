import { grouped, list, returnGroups, usd, wrapNames, type Messages } from "./types";

const lbp = (n: number) => `${grouped(n)} LBP`;
const join = (xs: string[]) => xs.join(", ");
const bullets = (xs: string[]) => xs.map((x) => `• ${x}`).join("\n");
const at = (when: string | null) => (when ? ` (${when})` : "");
const plural = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`;
/** The order number, always bold. */
const o = (code: string) => `*${code}*`;
/** SQL writes the paid amount as "9.44$ cash" (0121); in English the dollar sign goes first. */
const dollarFirst = (s: string) => s.replace(/(\d[\d,]*\.\d{2})\$/g, (_m, n: string) => `$${n}`);
/** "9.44$ cash" (0121) as "In cash · $9.44": the way, then the amount at the end of the line. */
const paid = (s: string) => { const m = /^(.+?) (cash|via Whish|via OMT)$/.exec(s.trim()); return m ? `${m[2]! === "cash" ? "In cash" : m[2]!.replace("via", "By")} · ${dollarFirst(m[1]!)}` : dollarFirst(s); };

